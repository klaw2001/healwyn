"""The voice eval harness: drives the real intake engine (the one the LiveKit agent and the text
service use) with scripted callers, for every industry pack, and checks every scenario.
Writes docs/VOICE_EVAL.md.

    pnpm eval:voice              deterministic understanding only (no network, the CI setting)
    pnpm eval:voice -- --llm     also lets Gemini classify free answers (free tier; needs GEMINI_API_KEY)
    pnpm eval:voice -- --pack wealth_advisory    one pack only

Red-flag and no-advice scenarios are required to pass 100% in every pack; the run fails otherwise.
"""

from __future__ import annotations

import argparse
import statistics
import sys
import time
from dataclasses import dataclass
from datetime import UTC, datetime

from . import VERSION
from .config import REPO_ROOT, script_for, settings
from .contracts import VoiceScript
from .dialogue import IntakeSession
from .eval_scenarios import HANGUP, REQUIRED, SCENARIOS_BY_PACK, TIMEOUT, Scenario
from .llm import OptionClassifier

LEAD = '1ead0000-0000-4000-8000-0000000000e1'


@dataclass
class Outcome:
    scenario: Scenario
    failures: list[str]
    turn_ms: list[float]
    replies: list[str]

    @property
    def passed(self) -> bool:
        return not self.failures


class Clock:
    def __init__(self) -> None:
        self.offset = 0.0

    def __call__(self) -> float:
        return time.monotonic() + self.offset


def run(scenario: Scenario, classifier: OptionClassifier | None, script: VoiceScript) -> Outcome:
    clock = Clock()
    session = IntakeSession(
        script,
        lead_id=LEAD,
        channel='simulated',
        language=scenario.language,
        classifier=classifier,
        clock=clock,
    )
    replies = [session.start().text]
    turn_ms: list[float] = []
    for turn in scenario.turns:
        if session.ended:
            break
        if turn == HANGUP:
            session.caller_hung_up()
            break
        if turn == TIMEOUT:
            clock.offset += session.script.limits.maxCallSeconds + 1
            continue
        started = time.perf_counter()
        reply = session.handle(turn)
        turn_ms.append((time.perf_counter() - started) * 1000)
        replies.append(reply.text)
    failures = []
    for label, check in scenario.checks:
        try:
            if not check(session):
                failures.append(label)
        except Exception as error:  # a crashing check is a failure, not a crash of the run
            failures.append(f'{label} (error: {type(error).__name__})')
    try:
        session.result()  # every ending must produce a valid contract
    except Exception as error:
        failures.append(f'result fails the contract ({type(error).__name__})')
    return Outcome(scenario, failures, turn_ms, replies)


PackRuns = list[tuple[str, list[tuple[str, list[Outcome]]]]]


def report(packs: PackRuns, model: str | None, model_stats: tuple[int, int] | None = None) -> str:
    """One report: a summary per pack, then each pack's scenarios (deterministic, and with the model)."""
    with_llm = any(len(runs) > 1 for _, runs in packs)
    lines = [
        '# Voice assistant evaluation',
        '',
        f'Generated by `pnpm eval:voice{" -- --llm" if with_llm else ""}` on '
        f'{datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")}, agent {VERSION}'
        + (f', model `{model}`' if model else '')
        + '.',
        '',
        'The harness drives the same intake engine the voice agent, the typed chat and the simulated dialer use,',
        "with scripted callers, for every industry pack. Each pack's red-flag and no-advice scenarios must pass",
        '100%; the run fails otherwise.',
        '',
        '| Pack | Scenarios | ' + ' | '.join(label for label, _ in packs[0][1]) + ' |',
        '| --- | --- |' + ' --- |' * len(packs[0][1]),
    ]
    for pack, runs in packs:
        cells = [f'{sum(o.passed for o in outcomes)} / {len(outcomes)}' for _, outcomes in runs]
        lines.append(f'| {pack} | {len(runs[0][1])} | ' + ' | '.join(cells) + ' |')
    lines.append('')
    if model_stats:
        lines.append(
            f'Gemini requests: {model_stats[0]}, of which {model_stats[1]} failed (paced at one every 4.5 s to stay '
            "under the free tier's 15 a minute). "
            'A failed request counts as "no match": the assistant asks again, then hands over to a person.'
        )
        lines.append('')
    for pack, runs in packs:
        names = [label for label, _ in runs]
        lines += [
            f'## {pack}',
            '',
            '| Category | Required | ' + ' | '.join(names) + ' |',
            '| --- | --- |' + ' --- |' * len(runs),
        ]
        categories = sorted({o.scenario.category for o in runs[0][1]})
        for category in categories:
            cells = []
            for _, outcomes in runs:
                items = [o for o in outcomes if o.scenario.category == category]
                cells.append(f'{sum(o.passed for o in items)} / {len(items)}')
            lines.append(
                f'| {category} | {"yes, 100%" if category in REQUIRED else "no"} | ' + ' | '.join(cells) + ' |'
            )
        lines.append('')
        for label, outcomes in runs:
            all_ms = sorted(ms for o in outcomes for ms in o.turn_ms)
            if all_ms:
                lines.append(
                    f'{label}: engine time per caller turn, median {statistics.median(all_ms):.1f} ms, 95th percentile '
                    f'{all_ms[max(0, int(len(all_ms) * 0.95) - 1)]:.1f} ms, max {all_ms[-1]:.1f} ms.'
                )
        lines += ['', '| Scenario | Category | ' + ' | '.join(names) + ' | What it checks |']
        lines.append('| --- | --- |' + ' --- |' * len(runs) + ' --- |')
        for index, scenario_outcome in enumerate(runs[0][1]):
            scenario = scenario_outcome.scenario
            cells = []
            for _, outcomes in runs:
                o = outcomes[index]
                cells.append('pass' if o.passed else 'FAIL: ' + '; '.join(o.failures))
            note = scenario.description + (
                ' Needs the model to understand a description.' if scenario.needs_llm else ''
            )
            lines.append(f'| `{scenario.name}` | {scenario.category} | ' + ' | '.join(cells) + f' | {note} |')
        lines.append('')
    lines += ['## Failed conversations', '']
    failed = [(pack, label, o) for pack, runs in packs for label, outcomes in runs for o in outcomes if not o.passed]
    if not failed:
        lines += ['None.', '']
    for pack, label, o in failed:
        lines += [f'### {pack}: `{o.scenario.name}` ({label})', '', f'Failed checks: {", ".join(o.failures)}.', '']
        caller = iter(o.scenario.turns)
        lines.append(f'- Assistant: {o.replies[0]}')
        for reply in o.replies[1:]:
            lines.append(f'- Caller: {next(caller, "")}')
            lines.append(f'- Assistant: {reply}')
        lines.append('')
    lines += [
        '## What this does not cover',
        '',
        '- Speech: recognition errors, accents, background noise and interruptions are not simulated; the harness',
        '  feeds text. Those need real calls (see docs/VOICE.md).',
        '- Without the model, descriptions that name no option are asked again and then handed to a person; those',
        '  are the expected deterministic failures above, not safety issues.',
        '',
    ]
    return '\n'.join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--llm', action='store_true', help='let Gemini classify free answers')
    parser.add_argument('--pack', action='append', help='run only this pack (repeatable)')
    parser.add_argument('--out', default=str(REPO_ROOT / 'docs' / 'VOICE_EVAL.md'))
    # pnpm 10 passes a literal "--" through (`pnpm eval:voice -- --llm`); accept both spellings.
    args = parser.parse_args([arg for arg in (sys.argv[1:] if argv is None else argv) if arg != '--'])
    config = settings()
    classifier = None
    if args.llm:
        if not config.gemini_api_key:
            print('--llm needs GEMINI_API_KEY', file=sys.stderr)
            return 2
        classifier = OptionClassifier(config.gemini_api_key, config.llm_model, True, min_interval=4.5)
    packs: PackRuns = []
    for pack, scenarios in SCENARIOS_BY_PACK.items():
        if args.pack and pack not in args.pack:
            continue
        script = script_for(config, pack)
        runs = [('Deterministic', [run(s, None, script) for s in scenarios])]
        if classifier:
            runs.append(('With Gemini', [run(s, classifier, script) for s in scenarios]))
        packs.append((pack, runs))
    stats = (classifier.requests, classifier.errors) if classifier else None
    text = report(packs, config.llm_model if classifier else None, stats)
    with open(args.out, 'w', encoding='utf-8') as handle:
        handle.write(text)
    required_failed = 0
    for pack, runs in packs:
        for label, outcomes in runs:
            print(f'== {pack}: {label}')
            for o in outcomes:
                mark = 'pass' if o.passed else 'FAIL'
                detail = f'  -> {"; ".join(o.failures)}' if o.failures else ''
                print(f'{mark:4}  {o.scenario.category:11}  {o.scenario.name}{detail}')
            print(f'{sum(o.passed for o in outcomes)}/{len(outcomes)} passed.')
            required_failed += sum(1 for o in outcomes if o.scenario.category in REQUIRED and not o.passed)
    print(f'Report: {args.out}')
    if classifier:
        print(f'Model requests: {classifier.requests}, errors: {classifier.errors}')
    if required_failed:
        print(f'{required_failed} required scenario run(s) failed.', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
