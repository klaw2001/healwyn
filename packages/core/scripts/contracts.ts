// Generates the TypeScript ↔ Python contracts.
//
//   pnpm contracts          write packages/core/contracts/* and apps/voice/healwyn_voice/contracts.py
//   pnpm contracts:check    regenerate into a temporary folder and fail if anything differs
//
// JSON Schema comes from the zod schemas in packages/core/src/voice/contract.ts;
// the voice script data file comes from each industry pack; the pydantic models
// come from the JSON Schema through datamodel-code-generator (pinned in
// apps/voice/requirements-dev.txt, run from apps/voice/.venv; see scripts/voice.sh).
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { z } from 'zod';
import { buildVoiceScript, industryPacks, voiceCallResultSchema, voiceScriptSchema } from '../src';

const root = join(import.meta.dirname, '../../..');
const check = process.argv.includes('--check');
const CONTRACTS = 'packages/core/contracts';
const PYTHON = 'apps/voice/healwyn_voice/contracts.py';

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function generate(outRoot: string) {
  const dir = join(outRoot, CONTRACTS);
  mkdirSync(dir, { recursive: true });
  const schemas = {
    'voice-script.schema.json': voiceScriptSchema,
    'voice-call-result.schema.json': voiceCallResultSchema,
  };
  for (const [file, schema] of Object.entries(schemas)) {
    const jsonSchema = z.toJSONSchema(schema, {
      target: 'draft-2020-12',
      // A `format` (uuid, date-time) already says it; pydantic cannot apply a pattern to UUID or datetime.
      override: (ctx) => {
        if (ctx.jsonSchema.format && ctx.jsonSchema.pattern) delete ctx.jsonSchema.pattern;
      },
    });
    writeFileSync(join(dir, file), json(jsonSchema));
  }
  for (const pack of Object.values(industryPacks)) {
    writeFileSync(join(dir, `voice-script.${pack.id}.json`), json(buildVoiceScript(pack)));
  }

  // Pydantic models: one module with both contracts.
  const codegen = join(root, 'apps/voice/.venv/bin/datamodel-codegen');
  const pyOut = join(outRoot, PYTHON);
  mkdirSync(join(pyOut, '..'), { recursive: true });
  const parts: string[] = [];
  for (const file of Object.keys(schemas)) {
    const tmp = join(mkdtempSync(join(tmpdir(), 'contracts-')), 'model.py');
    execFileSync(
      codegen,
      [
        '--input',
        join(dir, file),
        '--input-file-type',
        'jsonschema',
        '--output',
        tmp,
        '--output-model-type',
        'pydantic_v2.BaseModel',
        '--target-python-version',
        '3.12',
        '--use-standard-collections',
        '--use-union-operator',
        '--use-title-as-name',
        '--disable-timestamp',
        '--formatters',
        'builtin',
        '--use-double-quotes',
        '--field-constraints',
      ],
      { stdio: 'pipe' },
    );
    parts.push(readFileSync(tmp, 'utf8'));
    rmSync(join(tmp, '..'), { recursive: true, force: true });
  }
  writeFileSync(pyOut, mergePython(parts));
}

/** Joins generated modules: one header and merged import block, then each module's classes. */
function mergePython(parts: string[]): string {
  const fromImports = new Map<string, Set<string>>();
  const plainImports = new Set<string>();
  const bodies: string[] = [];
  for (const part of parts) {
    const body: string[] = [];
    for (const line of part.split('\n')) {
      if (line.startsWith('#')) continue;
      const from = /^from (\S+) import (.+)$/.exec(line);
      if (from) {
        const names = fromImports.get(from[1]!) ?? new Set<string>();
        for (const name of from[2]!.split(',')) names.add(name.trim());
        fromImports.set(from[1]!, names);
      } else if (line.startsWith('import ')) plainImports.add(line);
      else body.push(line);
    }
    bodies.push(body.join('\n').trim());
  }
  const future = fromImports.get('__future__');
  fromImports.delete('__future__');
  const imports = [
    ...(future ? [`from __future__ import ${[...future].sort().join(', ')}`, ''] : []),
    ...[...plainImports].sort(),
    ...[...fromImports.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([module, names]) => `from ${module} import ${[...names].sort().join(', ')}`),
  ];
  return [
    '# Generated by packages/core/scripts/contracts.ts from packages/core/contracts/*.schema.json. Do not edit.',
    '# Run `pnpm contracts` after changing packages/core/src/voice/contract.ts.',
    '',
    ...imports,
    '',
    '',
    bodies.join('\n\n\n'),
    '',
  ].join('\n');
}

function filesUnder(dir: string, prefix = ''): string[] {
  return readdirSync(join(dir, prefix), { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? filesUnder(dir, join(prefix, entry.name)) : [join(prefix, entry.name)],
  );
}

if (check) {
  const out = mkdtempSync(join(tmpdir(), 'contracts-check-'));
  try {
    generate(out);
    const stale: string[] = [];
    for (const file of [...filesUnder(join(out, CONTRACTS)).map((f) => join(CONTRACTS, f)), PYTHON]) {
      let current = '';
      try {
        current = readFileSync(join(root, file), 'utf8');
      } catch {
        /* missing counts as stale */
      }
      if (current !== readFileSync(join(out, file), 'utf8')) stale.push(file);
    }
    if (stale.length) {
      console.error(`Contracts are stale. Run \`pnpm contracts\` and commit:\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
    console.log('Contracts are up to date.');
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
} else {
  generate(root);
  console.log(`Wrote ${CONTRACTS}/ and ${PYTHON}.`);
}
