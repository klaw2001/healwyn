/**
 * What the wealth advisory assistant says and listens for. English and Hindi
 * (Devanagari plus common romanised Hinglish, since speech-to-text returns
 * either). Phrase lists are lower case and matched on word boundaries; a
 * Devanagari phrase may continue its last word ("माँग" matches "माँगा").
 *
 * Two rules shape everything here:
 * - The assistant never gives investment advice. It never names, rates or
 *   recommends a fund, stock, scheme, policy, product or cryptocurrency, never
 *   predicts returns, and never says how much or where to invest, whether to
 *   buy, sell or switch, or anything about tax or the law. It declines kindly
 *   and the intake continues.
 * - Fraud in progress is an emergency. Someone asking for an OTP, PIN or
 *   password, a remote-access app, a "digital arrest" or any threat demanding
 *   money now stops the intake: hang up on them, call 1930 or the bank, and 112
 *   if anyone is in danger. The red-flag list errs towards stopping: a false
 *   alarm costs a caller one sentence; a miss could cost their savings or more.
 */

